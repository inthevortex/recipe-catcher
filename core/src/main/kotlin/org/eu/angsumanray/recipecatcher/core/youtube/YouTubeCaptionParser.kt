package org.eu.angsumanray.recipecatcher.core.youtube

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.jsoup.Jsoup
import org.jsoup.parser.Parser

data class YouTubeCaptionTrack(
    val languageCode: String,
    val name: String?,
    val baseUrl: String,
    val isAutoGenerated: Boolean
)

object YouTubeCaptionParser {

    private val json = Json {
        ignoreUnknownKeys = true
        isLenient = true
    }

    private val NOISE_TAG_REGEX = Regex("""\[(?:music|applause|laughter|cheering|ambient noise|silence|sound)\]|\((?:music|applause|laughter|cheering)\)""", RegexOption.IGNORE_CASE)

    /**
     * Extracts available caption tracks from YouTube's ytInitialPlayerResponse JSON.
     */
    fun extractCaptionTracks(playerJsonString: String): List<YouTubeCaptionTrack> {
        val tracks = mutableListOf<YouTubeCaptionTrack>()
        try {
            val root = json.parseToJsonElement(playerJsonString).jsonObject
            val captions = root["captions"]?.jsonObject ?: return emptyList()
            val tracklistRenderer = captions["playerCaptionsTracklistRenderer"]?.jsonObject ?: return emptyList()
            val rawTracks = tracklistRenderer["captionTracks"]?.jsonArray ?: return emptyList()

            for (element in rawTracks) {
                val trackObj = element.jsonObject
                val baseUrl = trackObj["baseUrl"]?.jsonPrimitive?.contentOrNull ?: continue
                val langCode = trackObj["languageCode"]?.jsonPrimitive?.contentOrNull ?: "unknown"
                val kind = trackObj["kind"]?.jsonPrimitive?.contentOrNull
                val vssId = trackObj["vssId"]?.jsonPrimitive?.contentOrNull
                val isAsr = kind.equals("asr", ignoreCase = true) || vssId?.startsWith("a.") == true

                val name = trackObj["name"]?.jsonObject?.let { nameObj ->
                    nameObj["simpleText"]?.jsonPrimitive?.contentOrNull
                        ?: nameObj["runs"]?.jsonArray?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.contentOrNull
                }

                tracks.add(
                    YouTubeCaptionTrack(
                        languageCode = langCode,
                        name = name,
                        baseUrl = baseUrl,
                        isAutoGenerated = isAsr
                    )
                )
            }
        } catch (_: Exception) {
            // Malformed JSON or structure
        }
        return tracks
    }

    /**
     * Selects the most suitable track:
     * 1. Manual/standard English track
     * 2. Auto-generated English track
     * 3. First manual track
     * 4. First available track
     */
    fun pickPreferredCaptionTrack(tracks: List<YouTubeCaptionTrack>): YouTubeCaptionTrack? {
        if (tracks.isEmpty()) return null

        return tracks.firstOrNull { it.languageCode.startsWith("en", ignoreCase = true) && !it.isAutoGenerated }
            ?: tracks.firstOrNull { it.languageCode.startsWith("en", ignoreCase = true) }
            ?: tracks.firstOrNull { !it.isAutoGenerated }
            ?: tracks.firstOrNull()
    }

    /**
     * Parses timed-text transcript XML (standard format returned by YouTube's baseUrl)
     * and normalizes it into clean continuous paragraph text.
     */
    fun parseTimedTextXml(xml: String): String {
        if (xml.isBlank()) return ""

        val doc = Jsoup.parse(xml, "", Parser.xmlParser())
        val textElements = doc.select("text")

        val cleanLines = mutableListOf<String>()
        var previousLine = ""

        for (el in textElements) {
            val raw = el.text()
            val cleaned = cleanText(raw)
            if (cleaned.isNotBlank() && !cleaned.equals(previousLine, ignoreCase = true)) {
                cleanLines.add(cleaned)
                previousLine = cleaned
            }
        }

        return cleanLines.joinToString(" ")
    }

    /**
     * Parses timed-text transcript JSON3 format (returned when fmt=json3 is specified).
     */
    fun parseTimedTextJson(jsonString: String): String {
        if (jsonString.isBlank()) return ""

        val cleanLines = mutableListOf<String>()
        var previousLine = ""

        try {
            val root = json.parseToJsonElement(jsonString).jsonObject
            val events = root["events"]?.jsonArray ?: return ""

            for (event in events) {
                val segs = event.jsonObject["segs"]?.jsonArray ?: continue
                val textBuilder = StringBuilder()
                for (seg in segs) {
                    val utf8 = seg.jsonObject["utf8"]?.jsonPrimitive?.contentOrNull
                    if (!utf8.isNullOrBlank()) {
                        textBuilder.append(utf8)
                    }
                }
                val cleaned = cleanText(textBuilder.toString())
                if (cleaned.isNotBlank() && !cleaned.equals(previousLine, ignoreCase = true)) {
                    cleanLines.add(cleaned)
                    previousLine = cleaned
                }
            }
        } catch (_: Exception) {
            return ""
        }

        return cleanLines.joinToString(" ")
    }

    private fun cleanText(text: String): String {
        val withoutNoise = NOISE_TAG_REGEX.replace(text, " ")
        return withoutNoise
            .replace("\n", " ")
            .replace(Regex("""\s+"""), " ")
            .trim()
    }
}
