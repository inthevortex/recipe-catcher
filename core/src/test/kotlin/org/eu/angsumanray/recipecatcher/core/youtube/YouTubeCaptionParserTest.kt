package org.eu.angsumanray.recipecatcher.core.youtube

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YouTubeCaptionParserTest {

    private fun readFixture(filename: String): String {
        val stream = javaClass.getResourceAsStream("/youtube/$filename")
            ?: throw IllegalArgumentException("Fixture /youtube/$filename not found")
        return stream.bufferedReader().use { it.readText() }
    }

    @Test
    fun `extracts caption tracks from ytInitialPlayerResponse JSON`() {
        val playerJson = """
        {
          "captions": {
            "playerCaptionsTracklistRenderer": {
              "captionTracks": [
                {
                  "baseUrl": "https://www.youtube.com/api/timedtext?v=123&lang=en",
                  "name": { "simpleText": "English" },
                  "vssId": ".en",
                  "languageCode": "en",
                  "isTranslatable": true
                },
                {
                  "baseUrl": "https://www.youtube.com/api/timedtext?v=123&lang=en&kind=asr",
                  "name": { "simpleText": "English (auto-generated)" },
                  "vssId": "a.en",
                  "languageCode": "en",
                  "kind": "asr",
                  "isTranslatable": true
                },
                {
                  "baseUrl": "https://www.youtube.com/api/timedtext?v=123&lang=es",
                  "name": { "simpleText": "Spanish" },
                  "vssId": ".es",
                  "languageCode": "es",
                  "isTranslatable": true
                }
              ]
            }
          }
        }
        """.trimIndent()

        val tracks = YouTubeCaptionParser.extractCaptionTracks(playerJson)
        assertEquals(3, tracks.size)

        val manualEn = tracks[0]
        assertEquals("en", manualEn.languageCode)
        assertEquals("English", manualEn.name)
        assertFalse(manualEn.isAutoGenerated)

        val autoEn = tracks[1]
        assertEquals("en", autoEn.languageCode)
        assertTrue(autoEn.isAutoGenerated)

        val preferred = YouTubeCaptionParser.pickPreferredCaptionTrack(tracks)
        assertNotNull(preferred)
        assertEquals("https://www.youtube.com/api/timedtext?v=123&lang=en", preferred?.baseUrl)
        assertFalse(preferred?.isAutoGenerated == true)
    }

    @Test
    fun `picks auto-generated english if manual english is missing`() {
        val tracks = listOf(
            YouTubeCaptionTrack("es", "Spanish", "https://url/es", false),
            YouTubeCaptionTrack("en", "English (auto)", "https://url/en-asr", true)
        )
        val preferred = YouTubeCaptionParser.pickPreferredCaptionTrack(tracks)
        assertNotNull(preferred)
        assertEquals("https://url/en-asr", preferred?.baseUrl)
        assertTrue(preferred?.isAutoGenerated == true)
    }

    @Test
    fun `parses timedtext xml and removes noise tags`() {
        val xml = readFixture("youtube_timedtext_sample.xml")
        val transcript = YouTubeCaptionParser.parseTimedTextXml(xml)

        assertTrue(transcript.isNotBlank())
        assertFalse(transcript.contains("[Music]"))
        assertFalse(transcript.contains("[Applause]"))
        assertTrue(transcript.contains("Welcome back to the kitchen."))
        assertTrue(transcript.contains("Chicken Tikka Masala"))
        assertTrue(transcript.contains("500g chicken thighs"))
        assertTrue(transcript.contains("100ml heavy cream"))
    }

    @Test
    fun `parses timedtext json3 format`() {
        val json3 = """
        {
          "events": [
            {
              "tStartMs": 100,
              "dDurationMs": 2000,
              "segs": [
                { "utf8": "Hello " },
                { "utf8": "world! [Music]" }
              ]
            },
            {
              "tStartMs": 2200,
              "dDurationMs": 3000,
              "segs": [
                { "utf8": "Add 2 tsp salt." }
              ]
            }
          ]
        }
        """.trimIndent()

        val transcript = YouTubeCaptionParser.parseTimedTextJson(json3)
        assertEquals("Hello world! Add 2 tsp salt.", transcript)
    }

    @Test
    fun `returns empty for missing or invalid captions`() {
        assertEquals(emptyList<YouTubeCaptionTrack>(), YouTubeCaptionParser.extractCaptionTracks("{}"))
        assertEquals("", YouTubeCaptionParser.parseTimedTextXml(""))
        assertNull(YouTubeCaptionParser.pickPreferredCaptionTrack(emptyList()))
    }
}
